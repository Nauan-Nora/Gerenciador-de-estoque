import os
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import psycopg
from dotenv import load_dotenv, set_key
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict
from psycopg.rows import dict_row

from models import MovementType, Product, StockMovement, StockMovementError

PROJECT_ROOT = Path(__file__).resolve().parent.parent
ENVIRONMENT_FILE = PROJECT_ROOT / ".env"


class DatabaseConfigurationError(RuntimeError):
    pass


class ProductRepository:
    def __init__(self, database_url: str):
        self._database_url = database_url

    @classmethod
    def from_environment(cls) -> "ProductRepository":
        load_dotenv(ENVIRONMENT_FILE)
        database_url = os.getenv("DATABASE_URL", "").strip()
        if not database_url:
            raise DatabaseConfigurationError("A configuração do PostgreSQL ainda não foi feita.")
        return cls(database_url)

    @staticmethod
    def save_database_url(database_url: str) -> None:
        set_key(str(ENVIRONMENT_FILE), "DATABASE_URL", database_url, quote_mode="always")

    def _connect(self):
        return psycopg.connect(self._database_url, row_factory=dict_row)

    def initialize(self) -> None:
        self._ensure_database()
        with self._connect() as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS products (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    code VARCHAR(50) NOT NULL UNIQUE,
                    name VARCHAR(150) NOT NULL,
                    purchase_price NUMERIC(12, 2) NOT NULL
                        CHECK (purchase_price >= 0),
                    quantity INTEGER NOT NULL CHECK (quantity >= 0),
                    sale_price NUMERIC(12, 2) NOT NULL
                        CHECK (sale_price >= 0),
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """
            )
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS stock_movements (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
                    product_code VARCHAR(50) NOT NULL,
                    product_name VARCHAR(150) NOT NULL,
                    movement_type VARCHAR(7) NOT NULL
                        CHECK (movement_type IN ('ENTRADA', 'SAIDA', 'PERDA')),
                    quantity INTEGER NOT NULL CHECK (quantity > 0),
                    unit_cost NUMERIC(12, 2),
                    unit_sale_price NUMERIC(12, 2),
                    notes TEXT NOT NULL DEFAULT '',
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """
            )
            connection.execute(
                """
                ALTER TABLE stock_movements
                    ADD COLUMN IF NOT EXISTS unit_cost NUMERIC(12, 2),
                    ADD COLUMN IF NOT EXISTS unit_sale_price NUMERIC(12, 2)
                """
            )
            connection.execute(
                """
                ALTER TABLE stock_movements
                    DROP CONSTRAINT IF EXISTS stock_movements_movement_type_check
                """
            )
            connection.execute(
                """
                ALTER TABLE stock_movements
                    ADD CONSTRAINT stock_movements_movement_type_check
                    CHECK (movement_type IN ('ENTRADA', 'SAIDA', 'PERDA'))
                """
            )
            connection.execute(
                """
                CREATE INDEX IF NOT EXISTS stock_movements_created_at_idx
                ON stock_movements (created_at DESC)
                """
            )

    def _ensure_database(self) -> None:
        connection_info = conninfo_to_dict(self._database_url)
        database_name = connection_info.get("dbname")
        if not database_name or database_name == "postgres":
            return

        maintenance_info = dict(connection_info)
        maintenance_info["dbname"] = "postgres"
        with psycopg.connect(**maintenance_info, autocommit=True) as connection:
            exists = connection.execute(
                "SELECT 1 FROM pg_database WHERE datname = %s",
                (database_name,),
            ).fetchone()
            if not exists:
                connection.execute(
                    sql.SQL("CREATE DATABASE {}").format(sql.Identifier(database_name))
                )

    def list_products(self, search: str = "") -> list[Product]:
        with self._connect() as connection:
            rows = connection.execute(
                """
                WITH sales_30_days AS (
                    SELECT
                        movement.product_id,
                        SUM(movement.quantity) AS sold_quantity,
                        SUM(
                            movement.quantity
                            * COALESCE(movement.unit_sale_price, product.sale_price)
                        ) FILTER (WHERE movement.movement_type = 'SAIDA') AS revenue
                    FROM stock_movements AS movement
                    JOIN products AS product ON product.id = movement.product_id
                    WHERE movement.movement_type IN ('SAIDA', 'PERDA')
                      AND movement.created_at >= CURRENT_TIMESTAMP - INTERVAL '30 days'
                    GROUP BY movement.product_id
                ),
                ranked_sales AS (
                    SELECT
                        product_id,
                        sold_quantity,
                        revenue,
                        SUM(revenue) OVER () AS total_revenue,
                        SUM(revenue) OVER (
                            ORDER BY revenue DESC NULLS LAST, product_id
                            ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING
                        ) AS revenue_before
                    FROM sales_30_days
                )
                SELECT
                    product.id,
                    product.code,
                    product.name,
                    product.purchase_price,
                    product.quantity,
                    product.sale_price,
                    CASE
                        WHEN ranked.sold_quantity IS NULL THEN NULL
                        ELSE product.quantity * 30.0 / ranked.sold_quantity
                    END AS stock_days,
                    CASE
                        WHEN COALESCE(ranked.total_revenue, 0) = 0 THEN 'C'
                        WHEN COALESCE(ranked.revenue_before, 0)
                            < ranked.total_revenue * 0.80 THEN 'A'
                        WHEN COALESCE(ranked.revenue_before, 0)
                            < ranked.total_revenue * 0.95 THEN 'B'
                        ELSE 'C'
                    END AS abc_class
                FROM products AS product
                LEFT JOIN ranked_sales AS ranked ON ranked.product_id = product.id
                WHERE product.code ILIKE %s OR product.name ILIKE %s
                ORDER BY product.name, product.code
                """,
                (f"%{search}%", f"%{search}%"),
            ).fetchall()
        return [self._product_from_row(row) for row in rows]

    def get_product_by_code(self, code: str) -> Product | None:
        with self._connect() as connection:
            row = connection.execute(
                """
                SELECT id, code, name, purchase_price, quantity, sale_price
                FROM products
                WHERE code = %s
                """,
                (code.strip(),),
            ).fetchone()
        if row is None:
            return None
        row["stock_days"] = None
        row["abc_class"] = "C"
        return self._product_from_row(row)

    def get_summary(self) -> dict[str, int | Decimal]:
        with self._connect() as connection:
            row = connection.execute(
                """
                SELECT
                    COUNT(*) AS total_products,
                    COUNT(*) FILTER (WHERE product.quantity <= 5) AS low_stock,
                    COALESCE(
                        SUM(product.purchase_price * product.quantity), 0
                    )::numeric(14, 2) AS inventory_value,
                    COALESCE(
                        SUM(product.sale_price * product.quantity), 0
                    )::numeric(14, 2) AS potential_sales,
                    COALESCE(
                        SUM((product.sale_price - product.purchase_price) * product.quantity),
                        0
                    )::numeric(14, 2) AS potential_profit,
                    COALESCE(SUM(sales_30_days.revenue), 0)::numeric(14, 2)
                        AS revenue_30_days
                FROM products AS product
                LEFT JOIN (
                    SELECT
                        movement.product_id,
                        SUM(movement.quantity) AS sold_quantity,
                        SUM(
                            movement.quantity
                            * COALESCE(movement.unit_sale_price, product.sale_price)
                        ) FILTER (WHERE movement.movement_type = 'SAIDA') AS revenue
                    FROM stock_movements AS movement
                    JOIN products AS product ON product.id = movement.product_id
                    WHERE movement.movement_type IN ('SAIDA', 'PERDA')
                      AND movement.created_at >= CURRENT_TIMESTAMP - INTERVAL '30 days'
                    GROUP BY movement.product_id
                ) AS sales_30_days ON sales_30_days.product_id = product.id
                """
            ).fetchone()
        potential_sales = row["potential_sales"]
        return {
            "total_products": row["total_products"],
            "low_stock": row["low_stock"],
            "inventory_value": row["inventory_value"],
            "potential_sales": potential_sales,
            "potential_profit": row["potential_profit"],
            "margin_percent": (
                row["potential_profit"] * Decimal("100") / potential_sales
                if potential_sales
                else Decimal("0")
            ),
            "revenue_30_days": row["revenue_30_days"],
        }

    def add_product(self, product: Product) -> None:
        with self._connect() as connection:
            row = connection.execute(
                """
                INSERT INTO products
                    (code, name, purchase_price, quantity, sale_price)
                VALUES (%s, %s, %s, %s, %s)
                RETURNING id
                """,
                (
                    product.code,
                    product.name,
                    product.purchase_price,
                    product.quantity,
                    product.sale_price,
                ),
            ).fetchone()
            if product.quantity > 0:
                connection.execute(
                    """
                    INSERT INTO stock_movements
                        (product_id, product_code, product_name, movement_type,
                         quantity, unit_cost, notes)
                    VALUES (%s, %s, %s, 'ENTRADA', %s, %s, %s)
                    """,
                    (
                        row["id"],
                        product.code,
                        product.name,
                        product.quantity,
                        product.purchase_price,
                        "Estoque inicial",
                    ),
                )

    def update_product(self, product_id: int, product: Product) -> None:
        with self._connect() as connection:
            connection.execute(
                """
                UPDATE products
                SET code = %s,
                    name = %s,
                    sale_price = %s,
                    updated_at = CURRENT_TIMESTAMP
                WHERE id = %s
                """,
                (
                    product.code,
                    product.name,
                    product.sale_price,
                    product_id,
                ),
            )

    def register_movement(
        self,
        product_id: int,
        movement_type: MovementType,
        quantity: int,
        notes: str = "",
        purchase_unit_cost: Decimal | None = None,
    ) -> None:
        if movement_type not in ("ENTRADA", "SAIDA", "PERDA"):
            raise ValueError("Tipo de movimentação inválido.")
        if quantity <= 0:
            raise ValueError("A quantidade deve ser maior que zero.")
        if purchase_unit_cost is not None and purchase_unit_cost < 0:
            raise ValueError("O custo unitário não pode ser negativo.")

        with self._connect() as connection:
            product = connection.execute(
                """
                SELECT code, name, quantity, purchase_price, sale_price
                FROM products
                WHERE id = %s
                FOR UPDATE
                """,
                (product_id,),
            ).fetchone()
            if product is None:
                raise StockMovementError("O produto não foi encontrado.")
            is_entry = movement_type == "ENTRADA"
            if not is_entry and product["quantity"] < quantity:
                raise StockMovementError(
                    f"Estoque insuficiente. Disponível: {product['quantity']} unidade(s)."
                )

            unit_cost = product["purchase_price"]
            unit_sale_price = None
            new_quantity = (
                product["quantity"] + quantity
                if is_entry
                else product["quantity"] - quantity
            )
            if is_entry:
                unit_cost = (
                    purchase_unit_cost
                    if purchase_unit_cost is not None
                    else product["purchase_price"]
                )
                new_average_cost = (
                    (
                        product["purchase_price"] * product["quantity"]
                        + unit_cost * quantity
                    )
                    / new_quantity
                ).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
            else:
                new_average_cost = product["purchase_price"]
                if movement_type == "SAIDA":
                    unit_sale_price = product["sale_price"]
            connection.execute(
                """
                UPDATE products
                SET quantity = %s,
                    purchase_price = %s,
                    updated_at = CURRENT_TIMESTAMP
                WHERE id = %s
                """,
                (new_quantity, new_average_cost, product_id),
            )
            connection.execute(
                """
                INSERT INTO stock_movements
                    (product_id, product_code, product_name, movement_type, quantity,
                     unit_cost, unit_sale_price, notes)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (
                    product_id,
                    product["code"],
                    product["name"],
                    movement_type,
                    quantity,
                    unit_cost,
                    unit_sale_price,
                    notes.strip(),
                ),
            )

    def list_movements(
        self,
        product_id: int | None = None,
        limit: int = 500,
    ) -> list[StockMovement]:
        with self._connect() as connection:
            if product_id is None:
                rows = connection.execute(
                    """
                    SELECT id, product_id, product_code, product_name,
                           movement_type, quantity, notes, created_at,
                           unit_cost, unit_sale_price
                    FROM stock_movements
                    ORDER BY created_at DESC, id DESC
                    LIMIT %s
                    """,
                    (limit,),
                ).fetchall()
            else:
                rows = connection.execute(
                    """
                    SELECT id, product_id, product_code, product_name,
                           movement_type, quantity, notes, created_at,
                           unit_cost, unit_sale_price
                    FROM stock_movements
                    WHERE product_id = %s
                    ORDER BY created_at DESC, id DESC
                    LIMIT %s
                    """,
                    (product_id, limit),
                ).fetchall()
        return [
            StockMovement(
                id=row["id"],
                product_id=row["product_id"],
                product_code=row["product_code"],
                product_name=row["product_name"],
                movement_type=row["movement_type"],
                quantity=row["quantity"],
                notes=row["notes"],
                created_at=row["created_at"],
                unit_cost=row["unit_cost"],
                unit_sale_price=row["unit_sale_price"],
            )
            for row in rows
        ]

    def delete_product(self, product_id: int) -> None:
        with self._connect() as connection:
            connection.execute("DELETE FROM products WHERE id = %s", (product_id,))

    @staticmethod
    def _product_from_row(row) -> Product:
        return Product(
            id=row["id"],
            code=row["code"],
            name=row["name"],
            purchase_price=row["purchase_price"],
            quantity=row["quantity"],
            sale_price=row["sale_price"],
            stock_days=row["stock_days"],
            abc_class=row["abc_class"],
        )
